#!/usr/bin/env python3
r"""regen_registry.py — собирает REGISTRY.md из папок cases/.

Правило репозитория: реестр генерируется, а не пишется руками, поэтому он не может разойтись с кейсами.
Берёт из каждого cases/*/README.md: номер, название, дату, направление, статус, вердикт.
"""
from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CASES = ROOT / "cases"

DIRECTIONS = {
    "1": "code contribution",
    "2": "on-chain verification",
    "3": "bounties and tasks",
    "4": "grant applications",
    "5": "research artifacts",
    "6": "bug hunts",
}


def parse(readme: pathlib.Path) -> dict:
    text = readme.read_text(encoding="utf-8")
    title = next((l.lstrip("# ").strip() for l in text.splitlines() if l.startswith("# ")), readme.parent.name)

    def field(name: str) -> str:
        m = re.search(rf"\*\*{name}:\*\*\s*(.+)", text)
        return m.group(1).strip() if m else ""

    verdict = ""
    m = re.search(r"## Verdict\s*\n+(.+?)(?:\n\n|\Z)", text, re.S)
    if m:
        verdict = re.sub(r"\s+", " ", m.group(1)).strip()[:200]
    return {
        "folder": readme.parent.name,
        "number": readme.parent.name.split("-")[0],
        "title": title,
        "date": field("Date"),
        "status": field("Status"),
        "verdict": verdict,
    }


def main() -> int:
    rows = [parse(p) for p in sorted(CASES.glob("*/README.md"))]
    rows.sort(key=lambda r: r["number"])
    lines = [
        "# Registry",
        "",
        f"All cases, newest first. {len(rows)} entries. Generated by `tools/regen_registry.py`, do not edit by hand.",
        "",
        "| # | what was checked | result | date |",
        "|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda x: x["number"], reverse=True):
        short = r["title"].split("—", 1)[-1].strip() if "—" in r["title"] else r["title"]
        verdict = (r["verdict"] or "").replace("**", "")
        verdict = re.split(r"[.;]", verdict)[0][:110]
        date = (r["date"] or "").split("·")[0].strip()
        lines.append(f"| [{r['number']}](cases/{r['folder']}/README.md) | {short[:90]} | {verdict} | {date} |")
    (ROOT / "REGISTRY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"реестр обновлён: кейсов {len(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
